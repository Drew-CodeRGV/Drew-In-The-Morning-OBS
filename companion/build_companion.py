#!/usr/bin/env python3
"""Build the Companion page, blocks.json, and the manual fallback from obs-data.json.

    python3 companion/build_companion.py

The .companionconfig is a best-effort reconstruction of Companion's full-export
JSON (type "full", export version 6). It was not produced by clicking Export
inside Companion. See companion/README.md before importing it.
"""

from __future__ import annotations

import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent
DATA = ROOT / "obs-data.json"

# Scene names are the ones in OBS-setup.md. Source names are defined there
# for the Stream Deck path. They are not the Read-from-file files.
SCENE_HOST = "Main Host"
SCENE_JESS = "Host + Jess"
SOURCE_CHYRON = "DITM Chyron"
SOURCE_HEADLINE = "DITM Headline"
SOURCE_TITLE = "DITM Segment Title"
SOURCE_LETTER = "DITM Block Letter"
SOURCE_CARD = "DITM Block Card"
SOURCE_LOWER = "DITM Lower Third"

# Export version 6 is the Companion 3.5-era full export. Current Companion
# main (FILE_VERSION 12 as of the public Constants.ts on the default branch)
# upgrades older files on import and rejects files newer than itself.
# Companion 3.x builds older than 3.5 may reject version 6 as too new.
EXPORT_VERSION = 6
OBS_MODULE = "obs-studio"
OBS_LABEL = "obs"


def main() -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    blocks = load_blocks(data)
    (OUT / "blocks.json").write_text(json.dumps(blocks_document(blocks), indent=2) + "\n", encoding="utf-8")
    (OUT / "custom-variables.json").write_text(
        json.dumps(custom_variables(blocks), indent=2) + "\n", encoding="utf-8"
    )
    (OUT / "obs-websocket-requests.json").write_text(
        json.dumps(websocket_requests(blocks), indent=2) + "\n", encoding="utf-8"
    )
    (OUT / "ditm-showblocks.companionconfig").write_text(
        json.dumps(companion_config(blocks), indent=2) + "\n", encoding="utf-8"
    )
    (OUT / "button-table.md").write_text(button_table(blocks), encoding="utf-8")
    print(f"Wrote {len(blocks)} blocks to {OUT}")
    return 0


def load_blocks(data: dict) -> list[dict]:
    limit = int(data.get("chyronMaxChars") or 60)
    segments = sorted(data["segments"], key=lambda item: item["order"])
    if len(segments) != 13:
        raise SystemExit(f"Expected 13 blocks, found {len(segments)}")
    blocks = []
    for index, segment in enumerate(segments):
        letter = str(segment.get("letter") or segment["id"][:1]).upper()
        chyrons = segment.get("chyrons") or []
        headlines = segment.get("headlines") or []
        if not chyrons or not headlines:
            raise SystemExit(f"Block {letter} needs at least one chyron and one headline")
        primary = one_line(chyrons[0]["primary"])
        secondary = one_line(chyrons[0].get("secondary") or "")
        if len(primary) > limit or len(secondary) > limit:
            raise SystemExit(f"Block {letter} chyron exceeds {limit} characters")
        chyron = primary if not secondary else f"{primary}\n{secondary}"
        color = str(segment.get("color") or "#333333")
        blocks.append(
            {
                "index": index,
                "letter": letter,
                "id": segment["id"],
                "title": one_line(segment["title"]),
                "short": short_label(segment["title"]),
                "color": color,
                "colorInt": int(color.lstrip("#"), 16),
                "chyron": chyron,
                "headline": one_line(headlines[0]),
                "jess": bool(segment.get("jessDropIn")),
                "scene": SCENE_JESS if segment.get("jessDropIn") else SCENE_HOST,
            }
        )
    letters = [block["letter"] for block in blocks]
    if letters != list("ABCDEFGHIJKLM"):
        raise SystemExit(f"Block letters are {''.join(letters)}, expected A-M in order")
    return blocks


def one_line(value: str) -> str:
    return " ".join(str(value).split())


def short_label(title: str) -> str:
    head = title.split(":", 1)[0].strip()
    words = head.split()
    if not words:
        return title[:12]
    if len(words) == 1:
        return words[0][:12]
    two = f"{words[0]} {words[1]}"
    return two if len(two) <= 14 else words[0][:12]


def text_color(bg: int) -> int:
    red, green, blue = (bg >> 16) & 255, (bg >> 8) & 255, bg & 255
    luminance = 0.299 * red + 0.587 * green + 0.114 * blue
    return 0x14202B if luminance > 150 else 0xFFFFFF


def blocks_document(blocks: list[dict]) -> dict:
    return {
        "source": "obs-data.json",
        "note": "Generated by companion/build_companion.py. Do not edit.",
        "sources": {
            "chyron": SOURCE_CHYRON,
            "headline": SOURCE_HEADLINE,
            "segmentTitle": SOURCE_TITLE,
            "blockLetter": SOURCE_LETTER,
            "blockCard": SOURCE_CARD,
            "lowerThird": SOURCE_LOWER,
        },
        "scenes": {"host": SCENE_HOST, "jess": SCENE_JESS},
        "blocks": blocks,
    }


def custom_variables(blocks: list[dict]) -> dict:
    first = blocks[0]
    return {
        "ditm_block_index": {
            "description": "Current block index, 0 through 12. Arrow keys wrap.",
            "defaultValue": "0",
            "persistCurrentValue": False,
        },
        "ditm_block": {
            "description": "Current block letter.",
            "defaultValue": first["letter"],
            "persistCurrentValue": False,
        },
        "ditm_title": {
            "description": "Current segment title.",
            "defaultValue": first["title"],
            "persistCurrentValue": False,
        },
        "ditm_headline": {
            "description": "Current headline.",
            "defaultValue": first["headline"],
            "persistCurrentValue": False,
        },
        "ditm_chyron": {
            "description": "Current chyron, primary then secondary.",
            "defaultValue": first["chyron"],
            "persistCurrentValue": False,
        },
        "ditm_scene": {
            "description": "Main Host, or Host + Jess when the block has Jess.",
            "defaultValue": first["scene"],
            "persistCurrentValue": False,
        },
    }


def websocket_requests(blocks: list[dict]) -> dict:
    per_block = []
    for block in blocks:
        per_block.append(
            {
                "letter": block["letter"],
                "index": block["index"],
                "requests": text_requests(block) + scene_requests(block),
            }
        )
    return {
        "note": "OBS WebSocket v5 request bodies. overlay true keeps font and color. Password is not included.",
        "optionalImage": {
            "requestType": "SetInputSettings",
            "requestData": {
                "inputName": SOURCE_CARD,
                "inputSettings": {"file": "/absolute/path/to/a-card.png"},
                "overlay": True,
            },
            "comment": "Only if you add an image source named DITM Block Card. This repo has no per-block card art.",
        },
        "optionalVisibility": {
            "comment": "SetSceneItemEnabled needs the numeric sceneItemId from GetSceneItemId, not the source name.",
            "get": {
                "requestType": "GetSceneItemId",
                "requestData": {"sceneName": SCENE_HOST, "sourceName": SOURCE_LOWER},
            },
            "set": {
                "requestType": "SetSceneItemEnabled",
                "requestData": {"sceneName": SCENE_HOST, "sceneItemId": 0, "sceneItemEnabled": True},
            },
        },
        "blocks": per_block,
    }


def text_requests(block: dict | None, blank: bool = False) -> list[dict]:
    values = {
        SOURCE_CHYRON: "" if blank or block is None else block["chyron"],
        SOURCE_HEADLINE: "" if blank or block is None else block["headline"],
        SOURCE_TITLE: "" if blank or block is None else block["title"],
        SOURCE_LETTER: "" if blank or block is None else block["letter"],
    }
    return [
        {
            "requestType": "SetInputSettings",
            "requestData": {"inputName": name, "inputSettings": {"text": text}, "overlay": True},
        }
        for name, text in values.items()
    ]


def scene_requests(block: dict) -> list[dict]:
    return [
        {
            "requestType": "SetCurrentProgramScene",
            "requestData": {"sceneName": block["scene"]},
        }
    ]


def companion_config(blocks: list[dict]) -> dict:
    controls: dict[str, dict] = {}
    for block in blocks:
        row, column = divmod(block["index"], 5)
        controls.setdefault(str(row), {})[str(column)] = block_button(block)
    controls.setdefault("2", {})["3"] = arrow_button("PREV", -1, blocks)
    controls["2"]["4"] = arrow_button("NEXT", 1, blocks)
    controls.setdefault("0", {})["5"] = status_button()
    controls["0"]["6"] = clear_button()
    return {
        "version": EXPORT_VERSION,
        "type": "full",
        "companionBuild": "generated-not-exported",
        "pages": {
            "1": {
                "name": "DITM",
                "gridSize": {"minColumn": 0, "maxColumn": 7, "minRow": 0, "maxRow": 3},
                "controls": controls,
            }
        },
        "custom_variables": custom_variables(blocks),
        "instances": {
            "obs": {
                "label": OBS_LABEL,
                "moduleId": OBS_MODULE,
                "instance_type": OBS_MODULE,
                "enabled": True,
                "isFirstInit": False,
                "lastUpgradeIndex": -1,
                "config": {"host": "127.0.0.1", "port": 4455, "password": ""},
            }
        },
    }


def block_button(block: dict) -> dict:
    fg = text_color(block["colorInt"])
    actions = [
        set_var("ditm_block_index", str(block["index"]), 0),
        set_var("ditm_block", block["letter"], 0),
        set_var("ditm_title", block["title"], 0),
        set_var("ditm_headline", block["headline"], 0),
        set_var("ditm_chyron", block["chyron"], 0),
        set_var("ditm_scene", block["scene"], 0),
        obs_text(SOURCE_CHYRON, block["chyron"], 10),
        obs_text(SOURCE_HEADLINE, block["headline"], 10),
        obs_text(SOURCE_TITLE, block["title"], 10),
        obs_text(SOURCE_LETTER, block["letter"], 10),
        obs_scene(block["scene"], 20),
        obs_visibility(True, 30),
    ]
    return button(
        text=f"{block['letter']}\n{block['short']}",
        bgcolor=block["colorInt"],
        color=fg,
        actions=actions,
        feedback=index_feedback(block["index"]),
    )


def arrow_button(label: str, delta: int, blocks: list[dict]) -> dict:
    count = len(blocks)
    step = delta % count
    index_expr = f"($(internal:custom_ditm_block_index) + {step if delta > 0 else count - 1}) % {count}"
    actions = [
        set_expression("ditm_block_index", index_expr, 0),
        set_expression("ditm_block", ternary(blocks, "letter"), 30),
        set_expression("ditm_title", ternary(blocks, "title"), 30),
        set_expression("ditm_headline", ternary(blocks, "headline"), 30),
        set_expression("ditm_chyron", ternary(blocks, "chyron"), 30),
        set_expression("ditm_scene", ternary(blocks, "scene"), 30),
        obs_text(SOURCE_CHYRON, "$(internal:custom_ditm_chyron)", 80),
        obs_text(SOURCE_HEADLINE, "$(internal:custom_ditm_headline)", 80),
        obs_text(SOURCE_TITLE, "$(internal:custom_ditm_title)", 80),
        obs_text(SOURCE_LETTER, "$(internal:custom_ditm_block)", 80),
        obs_scene("$(internal:custom_ditm_scene)", 100),
        obs_visibility(True, 110),
    ]
    glyph = "▲ PREV" if delta < 0 else "▼ NEXT"
    return button(text=glyph, bgcolor=0x14202B, color=0xF6F1E7, actions=actions, feedback=None)


def status_button() -> dict:
    return button(
        text="$(internal:custom_ditm_block)\n$(internal:custom_ditm_title)",
        bgcolor=0x0E2433,
        color=0xE4B15A,
        actions=[],
        feedback=None,
    )


def clear_button() -> dict:
    actions = [
        set_var("ditm_chyron", "", 0),
        set_var("ditm_headline", "", 0),
        set_var("ditm_title", "", 0),
        obs_text(SOURCE_CHYRON, "", 10),
        obs_text(SOURCE_HEADLINE, "", 10),
        obs_text(SOURCE_TITLE, "", 10),
        obs_text(SOURCE_LETTER, "", 10),
    ]
    return button(text="CLEAR", bgcolor=0x3A2A2A, color=0xF6F1E7, actions=actions, feedback=None)


def button(text: str, bgcolor: int, color: int, actions: list[dict], feedback: dict | None) -> dict:
    return {
        "type": "button",
        "style": {
            "text": text,
            "size": "auto",
            "png64": None,
            "alignment": "center:center",
            "pngalignment": "center:center",
            "color": color,
            "bgcolor": bgcolor,
            "show_topbar": "default",
        },
        "options": {"relativeDelay": True, "stepAutoProgress": True},
        "feedbacks": [feedback] if feedback else [],
        "steps": {"0": {"options": {"runWhileHeld": []}, "action_sets": {"down": actions, "up": []}}},
    }


def index_feedback(index: int) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "type": "variable_value",
        "instance_id": "internal",
        "options": {
            "variable": "internal:custom_ditm_block_index",
            "op": "eq",
            "value": str(index),
        },
        "style": {"bgcolor": 0xFFFFFF, "color": 0x14202B},
        "isInverted": False,
    }


def set_var(name: str, value: str, delay: int) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "instance": "internal",
        "action": "custom_variable_set_value",
        "options": {"name": name, "value": value},
        "delay": delay,
    }


def set_expression(name: str, expression: str, delay: int) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "instance": "internal",
        "action": "custom_variable_set_expression",
        "options": {"name": name, "expression": expression},
        "delay": delay,
    }


def obs_text(source: str, text: str, delay: int) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "instance": OBS_LABEL,
        "action": "set_text",
        "options": {"source": source, "text": text},
        "delay": delay,
    }


def obs_scene(scene: str, delay: int) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "instance": OBS_LABEL,
        "action": "set_current_scene",
        "options": {"scene": scene},
        "delay": delay,
    }


def obs_visibility(enabled: bool, delay: int) -> dict:
    return {
        "id": str(uuid.uuid4()),
        "instance": OBS_LABEL,
        "action": "set_source_visibility",
        "options": {
            "scene": SCENE_HOST,
            "source": SOURCE_LOWER,
            "visible": enabled,
        },
        "delay": delay,
    }


def expr_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def ternary(blocks: list[dict], field: str) -> str:
    """Nested ternary on the block index. The last arm is the final block."""
    expr = expr_quote(str(blocks[-1][field]))
    for block in reversed(blocks[:-1]):
        expr = f"($(internal:custom_ditm_block_index) == {block['index']} ? {expr_quote(str(block[field]))} : {expr})"
    return expr


def button_table(blocks: list[dict]) -> str:
    lines = [
        "# Stream Deck button table",
        "",
        "Generated by `companion/build_companion.py`. Use this if the `.companionconfig` import does not land cleanly.",
        "",
        "15-key deck, top-left of the Companion page (5 columns, 3 rows):",
        "",
        "| Row | Col 0 | Col 1 | Col 2 | Col 3 | Col 4 |",
        "|---|---|---|---|---|---|",
    ]
    grid = [[""] * 5 for _ in range(3)]
    for block in blocks:
        row, column = divmod(block["index"], 5)
        grid[row][column] = f"**{block['letter']}** {block['short']}"
    grid[2][3] = "**PREV**"
    grid[2][4] = "**NEXT**"
    for row_index, row in enumerate(grid):
        lines.append(f"| {row_index} | " + " | ".join(row) + " |")
    lines.extend(
        [
            "",
            "32-key XL also shows, on the same page:",
            "",
            "- Row 0, column 5: STATUS. Button text `$(internal:custom_ditm_block)` and `$(internal:custom_ditm_title)`. No action.",
            "- Row 0, column 6: CLEAR. Sets the four DITM text sources to empty.",
            "",
            "A 15-key deck does not reach columns 5 and 6. Use the Companion emulator, or move those two buttons onto a second page.",
            "",
            "## What each block key does",
            "",
            "Set the custom variables, then send OBS WebSocket v5 `SetInputSettings` (overlay true) and `SetCurrentProgramScene`.",
            "",
            "| Key | Letter | Short | Color | Scene | Chyron (first) | Headline (first) | Title |",
            "|---|---|---|---|---|---|---|---|",
        ]
    )
    for block in blocks:
        chyron = block["chyron"].replace("\n", " / ").replace("|", "\\|")
        lines.append(
            "| {index} | {letter} | {short} | `{color}` | {scene} | {chyron} | {headline} | {title} |".format(
                index=block["index"],
                letter=block["letter"],
                short=block["short"].replace("|", "\\|"),
                color=block["color"],
                scene=block["scene"],
                chyron=chyron,
                headline=block["headline"].replace("|", "\\|"),
                title=block["title"].replace("|", "\\|"),
            )
        )
    lines.extend(
        [
            "",
            "## Variables",
            "",
            "Create these under Custom Variables (names must match):",
            "",
            "| Name | Default |",
            "|---|---|",
            "| `ditm_block_index` | `0` |",
            "| `ditm_block` | first block letter |",
            "| `ditm_title` | first block title |",
            "| `ditm_headline` | first headline |",
            "| `ditm_chyron` | first chyron |",
            "",
            "PREV expression for `ditm_block_index`:",
            "",
            "```",
            "($(internal:custom_ditm_block_index) + 12) % 13",
            "```",
            "",
            "NEXT expression:",
            "",
            "```",
            "($(internal:custom_ditm_block_index) + 1) % 13",
            "```",
            "",
            "Then set `ditm_block`, `ditm_title`, `ditm_headline`, and `ditm_chyron` from that index. The generated config uses nested ternaries. Give those actions about 30 ms of delay so they read the new index, and give the OBS text actions about 80 ms.",
            "",
            "Highlight: on each block key, add a feedback that checks `internal:custom_ditm_block_index` equals that key's index, and invert the colors.",
            "",
            "OBS source names: `DITM Chyron`, `DITM Headline`, `DITM Segment Title`, `DITM Block Letter`. Optional image `DITM Block Card`. Optional scene item `DITM Lower Third` on Main Host. Scenes: `Main Host` and `Host + Jess`.",
            "",
            "Do not turn on Read from file for the four DITM text sources. That mode ignores the websocket text.",
            "",
        ]
    )
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
